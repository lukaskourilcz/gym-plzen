export interface TermsSubitem {
  marker: string | null;
  text: string;
}

export interface TermsClause {
  number: string;
  text: string;
  subitems: TermsSubitem[];
}

export interface TermsSection {
  number: string;
  title: string;
  clauses: TermsClause[];
}

/** Parse the plain approved document into sections, clauses and nested lists. */
export function parseTermsBody(body: string): TermsSection[] {
  const sections: TermsSection[] = [];
  let current: TermsSection | null = null;

  for (const line of body.split("\n").map((value) => value.trim())) {
    if (!line) continue;

    const clause = line.match(/^(\d+\.\d+)\.\s+(.+)$/);
    if (clause && current) {
      current.clauses.push({
        number: clause[1]!,
        text: clause[2]!,
        subitems: [],
      });
      continue;
    }

    const heading = line.match(/^(\d+)\.\s+(.+)$/);
    if (heading) {
      if (current) sections.push(current);
      current = { number: heading[1]!, title: heading[2]!, clauses: [] };
      continue;
    }

    const previousClause = current?.clauses.at(-1);
    if (!previousClause) continue;

    const labeledItem = line.match(/^([a-z])\)\s+(.+)$/i);
    if (labeledItem) {
      previousClause.subitems.push({
        marker: labeledItem[1]!,
        text: labeledItem[2]!,
      });
      continue;
    }
    if (current?.number === "17" && previousClause.number === "17.1") {
      previousClause.subitems.push({ marker: null, text: line });
      continue;
    }
    if (line.startsWith("- ")) {
      previousClause.subitems.push({ marker: null, text: line.slice(2) });
      continue;
    }

    previousClause.text += `\n${line}`;
  }

  if (current) sections.push(current);
  return sections;
}
