export interface RuleClause {
  number: string;
  text: string;
}

export interface RuleSection {
  number: string;
  title: string;
  clauses: RuleClause[];
}

/** Parse the deliberately plain CMS document into semantic page sections. */
export function parseRulesBody(body: string): RuleSection[] {
  const sections: RuleSection[] = [];
  let current: RuleSection | null = null;

  for (const block of body.split(/\n+/).map((value) => value.trim())) {
    if (!block) continue;

    const clause = block.match(/^(\d+\.\d+)\.\s+(.+)$/);
    if (clause && current) {
      current.clauses.push({ number: clause[1]!, text: clause[2]! });
      continue;
    }

    const heading = block.match(/^(\d+)\.\s+(.+)$/);
    if (heading) {
      if (current) sections.push(current);
      current = { number: heading[1]!, title: heading[2]!, clauses: [] };
      continue;
    }

    // Preserve a manually wrapped continuation from the CMS instead of
    // silently dropping it when an administrator reformats a long clause.
    const previousClause = current?.clauses.at(-1);
    if (previousClause) previousClause.text += ` ${block}`;
  }

  if (current) sections.push(current);
  return sections;
}
